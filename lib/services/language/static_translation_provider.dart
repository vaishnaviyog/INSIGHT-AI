  @override
  Future<TranslationResult> translate(String englishText, SupportedLanguage targetLanguage) async {
    if (targetLanguage == SupportedLanguage.english) {
      return TranslationResult(englishText, wasTranslated: false);
    }

    // 1. Exact fixed one-liners.
    final exact = _exactPhrases[englishText]?[targetLanguage];
    if (exact != null) return TranslationResult(exact, wasTranslated: true);

    // 2. Hazard-warning shapes from AdaptiveGuidanceService._buildMessage.

    // 2a. Critical, WITH a distance estimate:
    // "Urgent! {Noun} {ahead/on your left/on your right}. Approximately
    // {n} meters. Be careful."
    final urgentWithDistance = RegExp(
      r'^Urgent! (.+?) (ahead|on your left|on your right)\. '
      r'Approximately ([\d.]+) meters\. Be careful\.$',
    ).firstMatch(englishText);
    if (urgentWithDistance != null) {
      final translatedNoun = _nouns[urgentWithDistance.group(1)!.toLowerCase()]?[targetLanguage];
      final positionT = _visionPositionPhrases[urgentWithDistance.group(2)]?[targetLanguage];
      final distanceT = _distanceClauseTemplate[targetLanguage];
      final beCarefulT = _beCarefulPhrase[targetLanguage];
      if (translatedNoun != null && positionT != null && distanceT != null && beCarefulT != null) {
        return TranslationResult(
          '$translatedNoun $positionT. '
          '${distanceT.replaceAll('{n}', urgentWithDistance.group(3)!)} $beCarefulT',
          wasTranslated: true,
        );
      }
    }

    // 2b. Critical, WITHOUT a distance estimate (label has no known
    // height configured): "Urgent! {Noun} very close, be careful."
    final urgentNoDistance =
        RegExp(r'^Urgent! (.+) very close, be careful\.$').firstMatch(englishText);
    if (urgentNoDistance != null) {
      final noun = urgentNoDistance.group(1)!.toLowerCase();
      final translatedNoun = _nouns[noun]?[targetLanguage];
      final template = _urgentTemplate[targetLanguage];
      if (translatedNoun != null && template != null) {
        return TranslationResult(
          template.replaceAll('{object}', translatedNoun),
          wasTranslated: true,
        );
      }
    }

    // 2c. Every other tier — short form and standard/"Caution," form,
    // with or without a distance clause — all share one shape:
    // "[Caution, ]{Noun} {ahead/on your left/on your right}.[ Approximately {n} meters.]"
    final standardMatch = RegExp(
      r'^(Caution, )?(.+?) (ahead|on your left|on your right)\.'
      r'(?: Approximately ([\d.]+) meters\.)?$',
    ).firstMatch(englishText);
    if (standardMatch != null) {
      final hasCaution = standardMatch.group(1) != null;
      final translatedNoun = _nouns[standardMatch.group(2)!.toLowerCase()]?[targetLanguage];
      final positionT = _visionPositionPhrases[standardMatch.group(3)]?[targetLanguage];
      final distanceGroup = standardMatch.group(4);
      if (translatedNoun != null && positionT != null) {
        final cautionT = hasCaution ? _cautionWord[targetLanguage] : null;
        if (hasCaution && cautionT == null) {
          // Missing translation for the "Caution," word specifically —
          // honest fallback rather than silently dropping it.
        } else {
          final distanceClause = distanceGroup == null
              ? ''
              : _distanceClauseTemplate[targetLanguage]?.replaceAll('{n}', distanceGroup);
          if (distanceGroup == null || distanceClause != null) {
            final sentence = '$translatedNoun $positionT.';
            final result = hasCaution ? '$cautionT $sentence' : sentence;
            return TranslationResult(
              distanceClause != null && distanceClause.isNotEmpty
                  ? '$result $distanceClause'
                  : result,
              wasTranslated: true,
            );
          }
        }
      }
    }

    // 3. SOS countdown, with the seconds count kept as a plain number.
    final sosMatch = RegExp(r'^S O S will be sent in (\d+) seconds\. Tap again to cancel\.$')
        .firstMatch(englishText);
    if (sosMatch != null) {
      final template = _sosCountdownTemplate[targetLanguage];
      if (template != null) {
        return TranslationResult(
          template.replaceAll('{n}', sosMatch.group(1)!),
          wasTranslated: true,
        );
      }
    }

    // 4. Turn-by-turn instructions from LocationService._constructInstruction.
    final turnResult = _translateTurnInstruction(englishText, targetLanguage);
    if (turnResult != null) return TranslationResult(turnResult, wasTranslated: true);

    // 5. "The road is <direction>, [about] N meters away."
    final roadIsMatch =
        RegExp(r'^The road is (.+?), (?:about )?(\d+) meters away\.$').firstMatch(englishText);
    if (roadIsMatch != null) {
      final dirT = _directionPhrases[roadIsMatch.group(1)]?[targetLanguage];
      final roadT = _roadIsPrefix[targetLanguage];
      final clauseT = _metersAwayClause[targetLanguage];
      if (dirT != null && roadT != null && clauseT != null) {
        return TranslationResult(
          '$roadT $dirT, ${roadIsMatch.group(2)} $clauseT.',
          wasTranslated: true,
        );
      }
    }

    // 6. "The route is now <direction>."
    final routeNowMatch = RegExp(r'^The route is now (.+)\.$').firstMatch(englishText);
    if (routeNowMatch != null) {
      final dirT = _directionPhrases[routeNowMatch.group(1)]?[targetLanguage];
      final prefixT = _routeIsNowPrefix[targetLanguage];
      if (dirT != null && prefixT != null) {
        return TranslationResult('$prefixT $dirT.', wasTranslated: true);
      }
    }

    // 7. "The route continues <direction>. <rest>"
    final continuesMatch = RegExp(r'^The route continues (.+?)\. (.*)$').firstMatch(englishText);
    if (continuesMatch != null) {
      final dirT = _directionPhrases[continuesMatch.group(1)]?[targetLanguage];
      final prefixT = _routeContinuesPrefix[targetLanguage];
      final suffixT = _routeContinuesSuffix[targetLanguage];
      final rest = continuesMatch.group(2)!;
      if (dirT != null && prefixT != null && suffixT != null) {
        if (rest.isEmpty) {
          return TranslationResult('$prefixT $dirT $suffixT', wasTranslated: true);
        }
        final restResult = await translate(rest, targetLanguage);
        if (restResult.wasTranslated) {
          return TranslationResult(
            '$prefixT $dirT $suffixT ${restResult.text}',
            wasTranslated: true,
          );
        }
        // The rest didn't translate — speaking a translated prefix
        // immediately followed by an untranslated English clause,
        // under this language's TTS voice, would mispronounce it.
        // Leave the WHOLE message in English rather than mixing.
        return TranslationResult(englishText, wasTranslated: false);
      }
    }

    // 8. Mid-sentence " Then, <rest>" connector (chains a second
    // instruction onto the current one — see `_fetchRoute`).
    const thenMarker = ' Then, ';
    final thenIdx = englishText.indexOf(thenMarker);
    if (thenIdx != -1) {
      final connectorT = _thenConnector[targetLanguage];
      if (connectorT != null) {
        final head = englishText.substring(0, thenIdx); // up to, excluding, the marker's leading space
        final tail = englishText.substring(thenIdx + thenMarker.length);
        final headResult = await translate(head, targetLanguage);
        final tailResult = await translate(tail, targetLanguage);
        if (headResult.wasTranslated && tailResult.wasTranslated) {
          return TranslationResult(
            '${headResult.text}$connectorT${tailResult.text}',
            wasTranslated: true,
          );
        }
        // One side didn't translate — a Tamil/Hindi/Malayalam/Telugu
        // clause stitched to an untranslated English clause, spoken
        // in one non-English voice, is worse than plain English.
        return TranslationResult(englishText, wasTranslated: false);
      }
    }

    // 9. Known sentence prefixes — translate the prefix, recursively
    // attempt the remainder. Only reported as translated when the
    // remainder ALSO genuinely translated (or is empty) — otherwise
    // this would speak a translated prefix immediately followed by an
    // untranslated English clause (e.g. the safety-route explanation,
    // or a longer free-text tail) under the target language's TTS
    // voice, which mispronounces it. A short destination/street name
    // tail is the one case this is a little conservative about (it
    // reverts the whole line to English rather than accepting one
    // foreign proper noun mid-sentence) — deliberately: better to
    // under-translate than to produce a broken mixed-voice sentence.
    for (final entry in _prefixes.entries) {
      if (englishText.startsWith(entry.key)) {
        final prefixT = entry.value[targetLanguage];
        if (prefixT == null) continue;
        final rest = englishText.substring(entry.key.length);
        if (rest.isEmpty) return TranslationResult(prefixT, wasTranslated: true);
        final restResult = await translate(rest, targetLanguage);
        if (restResult.wasTranslated) {
          return TranslationResult('$prefixT${restResult.text}', wasTranslated: true);
        }
        return TranslationResult(englishText, wasTranslated: false);
      }
    }

    // Not recognized — honest fallback (see class doc comment).
    return TranslationResult(englishText, wasTranslated: false);
  }

  static final RegExp _turnWithStreet = RegExp(
    r'^(?<action>Turn|Head|Walk)(?: (?<dir>[a-zA-Z]+(?: [a-zA-Z]+)?))? onto (?<street>.+?)(?: for (?<dist>\d+) meters)?\.$',
  );
  static final RegExp _turnWithoutStreet = RegExp(
    r'^(?<action>Turn|Head|Walk)(?: (?<dir>[a-zA-Z]+(?: [a-zA-Z]+)?))?(?: for (?<dist>\d+) meters)?\.$',
  );

  String? _translateTurnInstruction(String text, SupportedLanguage lang) {
    final match = _turnWithStreet.firstMatch(text) ?? _turnWithoutStreet.firstMatch(text);
    if (match == null) return null;

    final action = match.namedGroup('action');
    final dir = match.namedGroup('dir');
    final street = match.namedGroup('street');
    final dist = match.namedGroup('dist');
    if (action == null) return null;

    final actionT = _actionWords[action.toLowerCase()]?[lang];
    if (actionT == null) return null;

    String? dirT;
    if (dir != null) {
      dirT = _turnDirections[dir.toLowerCase()]?[lang];
      if (dirT == null) return null; // unrecognized modifier — honest bail
    }

    final parts = <String>[];
    if (street != null) {
      final ontoT = _ontoPostposition[lang];
      if (ontoT == null) return null;
      parts.add('$street $ontoT');
    }
    if (dirT != null) parts.add(dirT);
    parts.add(actionT);

    var sentence = parts.join(' ');
    if (dist != null) {
      final metersT = _metersForClause[lang];
      if (metersT == null) return null;
      sentence += ', $dist $metersT';
    }
    return '$sentence.';
  }
