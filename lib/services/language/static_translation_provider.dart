///     the street name (a proper noun) and the distance number are
///     kept as-is
///   - the "road is <direction>, N meters away" / "route is now
///     <direction>" GPS progress announcements from `navigation_screen.dart`
///   - common sentence prefixes ("Route found.", "This route was
///     chosen for safety.", "Calculating route to", "Proceed to the
///     road first.", "You are moving away.", " Then, ") — translated,
///     with the remainder of the sentence recursively translated too
///     where possible
///
/// STILL NOT TRANSLATED, ON PURPOSE (honest fallback — returns the
/// original English text with `wasTranslated: false`, so
/// [LanguageService.speak] keeps the English voice rather than
/// mispronouncing it): free-form scene descriptions, the safety-route
/// explanation text, recognized speech (destination names), and any
/// phrasing that doesn't match one of the templates above. A real
/// machine-translation API is the correct way to cover those; see
/// [ITranslationProvider]'s doc comment for how to swap one in.
