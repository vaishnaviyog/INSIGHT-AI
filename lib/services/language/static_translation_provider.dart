import 'translation_provider.dart';

/// Offline, dictionary-based [ITranslationProvider]. No network, no
/// API key.
///
/// IMPORTANT, FLAGGED EXPLICITLY: the phrases below are reasonable-
/// effort, common-vocabulary translations, NOT verified by a native
/// speaker of Tamil, Hindi, Malayalam, or Telugu. For a safety-
/// relevant accessibility application, incorrect or awkward warning
/// phrasing is a real hazard, not a cosmetic issue. Treat this as a
/// working scaffold that demonstrates the pipeline end-to-end, not a
/// finished localization — have each language reviewed by a native
/// speaker before relying on it.
///
/// COVERAGE (this is the honest scope):
///   - hazard warnings in their current shape: "{noun} {ahead/on your
///     left/on your right}." optionally prefixed with "Caution, " or
///     "Urgent! " and suffixed with an "Approximately N meters." /
///     "Be careful." clause — see `AdaptiveGuidanceService._buildMessage`
///     for the exact shapes this matches
///   - fixed one-line system prompts (onboarding-independent UI text:
///     "Analyzing scene", "Checking...", SOS messages, route-not-found
///     messages, arrival, etc.)
///   - turn-by-turn instructions generated by `LocationService`
///     (`_constructInstruction`) — these follow a fixed
///     "<Turn/Head/Walk> <modifier> onto <street> for <N> meters."
